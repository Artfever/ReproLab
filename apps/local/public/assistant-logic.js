// assistant-logic.js: DOM-free helpers for the assistant panel (spec 03-local-product, task 6.4).
// Requirements 13.5, 14.4 to 14.6. Runs in the browser and under node:test.
// Everything here returns plain data. assistant.js inserts it with textContent only.

export const QUESTION_MAX = 500; // Requirement 12.8.
export const ANSWER_LABEL = 'Generated by a language model from the cited passages. Check the citations.';
export const STATUS_UNREADABLE = 'The assistant status could not be read from the local server.';
export const SERVER_UNREACHABLE = 'The local server could not be reached. Check that it is still running.';
export const STATUS_URL = '/api/assistant/status';
export const ASK_URL = '/api/assistant/ask';

/** What the panel shows for a GET /api/assistant/status result. */
export function statusView(httpStatus, json) {
  if (httpStatus === 200 && json && typeof json === 'object') {
    const reason = typeof json.reason === 'string' ? json.reason : '';
    if (json.status === 'enabled') return { enabled: true, reason };
    if (json.status === 'disabled') return { enabled: false, reason: reason || STATUS_UNREADABLE };
  }
  return { enabled: false, reason: STATUS_UNREADABLE };
}

/** Client-side check. Returns {ok:true, question} or {ok:false, message}. */
export function checkQuestion(raw) {
  const q = String(raw ?? '').trim();
  if (q === '') return { ok: false, message: 'Type a question first.' };
  if (q.length > QUESTION_MAX) {
    return { ok: false, message: `The question is ${q.length} characters long. The limit is ${QUESTION_MAX}.` };
  }
  return { ok: true, question: q };
}

/** Request body for POST /api/assistant/ask. runId is included only when present. */
export function askBody(question, runId) {
  return runId ? { question, runId } : { question };
}

/**
 * What the panel shows for a POST /api/assistant/ask result.
 * kind is 'answer' (with label and citations), 'declined' or 'error'. `text` is plain text.
 */
export function answerView(httpStatus, json) {
  const j = json && typeof json === 'object' && !Array.isArray(json) ? json : {};
  if (httpStatus === 200 && j.kind === 'answer' && typeof j.text === 'string' && Array.isArray(j.citations)) {
    const citations = j.citations
      .filter((c) => c && typeof c.id === 'string' && typeof c.text === 'string')
      .map((c) => ({ id: c.id, source: typeof c.source === 'string' ? c.source : '', text: c.text }));
    return { kind: 'answer', text: j.text, label: ANSWER_LABEL, citations };
  }
  if (httpStatus === 200 && j.kind === 'declined' && typeof j.message === 'string') {
    return { kind: 'declined', text: j.message, citations: [] };
  }
  const message = typeof j.message === 'string' ? j.message : typeof j.error === 'string' ? j.error : null;
  return {
    kind: 'error',
    text: message ?? `The assistant could not answer (the local server replied with status ${httpStatus}).`,
    citations: [],
  };
}
